"""## Core Function: `execute_workflow`

Accepts `user_request` (natural language), starts a new thread, and drives the graph through any
number of interrupt/resume cycles. `simulated_responses` is a queue of simulated human decisions
(used by the test cases below); if omitted, it falls back to real `input()`.
"""

def execute_workflow(
    user_request: str,
    simulated_responses: Optional[list[dict]] = None,
    autopilot: bool = False,
    max_files: int = 5,
    verbose: bool = True,
) -> dict:
    """Run one planner -> human-review -> downloader -> report cycle for `user_request`.

    Args:
        user_request: what to fetch, e.g. "daily 1d candles for BTCUSDT, last 5 days".
        simulated_responses: queue of {"approved": bool, "feedback": str} dicts, consumed in
            order each time the graph interrupts. Ignored entirely when autopilot=True.
        autopilot: if True, the human_review node auto-approves the first plan without pausing --
            useful for unattended/batch runs.
        max_files: safety cap on how many archives can be downloaded in one run. Controlled here,
            not by the LLM, regardless of how large a range the user asked for.
        verbose: print progress as the workflow runs.

    Returns:
        The final graph state, including the approved draft_report and download_summary.
    """
    thread_id = str(uuid.uuid4())
    config = {"configurable": {"thread_id": thread_id}}

    initial_state: SystemState = {
        "user_request": user_request,
        "plan": None,
        "human_decision": {},
        "feedback_history": [],
        "download_summary": None,
        "draft_report": "",
        "autopilot": autopilot,
        "max_files": max_files,
        "messages": [HumanMessage(content=user_request)],
    }

    queue = list(simulated_responses) if simulated_responses is not None else None

    if verbose:
        mode = "AUTOPILOT" if autopilot else "INTERACTIVE"
        print(f"=== Starting workflow (thread {thread_id[:8]}, mode={mode}, max_files={max_files}) ===")
        print(f"Request: {user_request}\n")

    result = graph.invoke(initial_state, config=config)

    round_num = 1
    while "__interrupt__" in result:
        payload = result["__interrupt__"][0].value
        if verbose:
            print(f"--- HUMAN REVIEW (round {round_num}) ---")
            print(json.dumps(payload, indent=2, ensure_ascii=False))
            print()

        if queue:
            human_response = queue.pop(0)
        else:
            approved_raw = input("Approve this plan? (y/n): ").strip().lower()
            approved = approved_raw == "y"
            feedback = "" if approved else input("What should change? ")
            human_response = {"approved": approved, "feedback": feedback}

        if verbose:
            verdict = "APPROVED" if human_response.get("approved") else "REVISION REQUESTED"
            print(f">>> Human decision: {verdict}"
                  + (f" -- '{human_response.get('feedback')}'" if not human_response.get("approved") else ""))
            print()

        result = graph.invoke(Command(resume=human_response), config=config)
        round_num += 1

    if verbose:
        print("=== Final Report ===")
        print(result["draft_report"])

    return result

