@tool
def validate_symbol(symbol: str) -> str:

    """
    Validate a Binance Spot trading pair.
    Checks via the public Binance REST API whether the symbol actually exists, before we plan to download data for it.
    """
    #TODO need to update validate_symbol to be used with different exchange not only Binance

    symbol = symbol.upper().strip()

    try:
        response = requests.get(
            "https://api.binance.com/api/v3/exchangeInfo",
            params={"symbol": symbol},
            timeout=10,
        )

        if response.status_code == 200:
            data = response.json()
            valid = bool(data.get("symbols"))

            return json.dumps({
                "symbol": symbol,
                "valid": valid,
                "status": ("found" if valid else "not_found"),
            })

        if response.status_code == 451:

            return json.dumps({
                "symbol": symbol,
                "valid": None,
                "status": "unavailable",
                "reason": (
                    "Binance returned HTTP 451. "
                    "Symbol validity could not be confirmed."
                ),
            })

        return json.dumps({
            "symbol": symbol,
            "valid": None,
            "status": f"http_{response.status_code}",
        })

    except Exception as e:

        return json.dumps({
            "symbol": symbol,
            "valid": None,
            "status": "error",
            "reason": str(e)[:100],
        })



@tool
def fetch_and_store_candles(symbol: str, interval: str, period_type: str, period_label: str) -> str:

    """
    Download one Binance historical candle archive and store the resulting pandas DataFrame in memory.
    """

    try:
        df, summary = download_binance_candles(symbol=symbol, interval=interval, period_type=period_type, period_label=period_label)

        if df is None:
            return json.dumps(summary)

        key = (f"{symbol}_{interval}_{period_label}")
        downloaded_data[key] = df

        return json.dumps({
            **summary,
            "data_key": key,
            "columns": list(df.columns),
        })

    except Exception as e:
        return json.dumps({
            "symbol": symbol,
            "interval": interval,
            "period_type": period_type,
            "period_label": period_label,
            "status": "error",
            "error": str(e),
        })

