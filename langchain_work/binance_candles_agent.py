"""## Agent 1 -- Planner

**Role:** turns the natural-language request into a structured `DownloadPlan`. Uses
`validate_symbol` to check the symbol is real before finalizing the plan. If there's feedback
from an earlier review round, it's folded into the new plan.
"""

def planner(state: SystemState) -> dict:

    user_request = state.get("user_request")

    if not user_request:
        return {"plan": None, "messages": []}

    today_iso = date.today().isoformat()
    exchange = state["exchange"]
    feedback_history = state.get("feedback_history", [])

    planner_prompt = f"""
You are the Planner Agent.

Your role is to create a DownloadPlan for downloading
historical cryptocurrency data from Binance.

Today's date is {today_iso}.

Available exchange:{exchange.name}

Supported symbols:{exchange.symbols}

Supported intervals:{exchange.intervals}

Supported archive period types:{exchange.period_types}

Exchange notes:{exchange.notes or "None"}

IMPORTANT RULES:

1. You MUST use the validate_symbol tool to validate
   the requested trading pair.

2. The original user request is:{user_request}

3. If there is human reviewer feedback from a previous
   planning attempt, that feedback MUST be applied to
   the new plan.

4. Human reviewer feedback has priority over the
   corresponding part of the original user request.

5. For example, if the original request says:

   "Download BTCUSDC 1h data..."

   and the human says:

   "Please use ETHUSDC instead of BTCUSDC."

   then the NEW plan MUST use:

   symbol = ETHUSDC

6. Do not keep the old value when the human explicitly
   asks you to change it.

7. Do not silently change values that the human did not
   ask to change.

8. If the reviewer changes the symbol, validate the NEW
   symbol using validate_symbol.

9. If the reviewer changes the interval, use the NEW
   interval.

10. If the reviewer changes the date range, use the NEW
    date range.

11. Do not download any data. Your job is only to create
    the plan.

12. Return a structured DownloadPlan.
"""

    if feedback_history:

        planner_prompt += """

HUMAN REVIEWER FEEDBACK:
The previous plan was rejected.
The following feedback MUST be applied to the new plan:

"""

        planner_prompt += "\n".join(f"- {feedback}" for feedback in feedback_history)

    # Create a fresh planner agent with
    # the dynamic exchange/feedback prompt.

    planner_agent = create_agent(
        model=ChatOpenAI(
            model="gpt-5.6-luna",
            api_key=openai_api_key,
            reasoning_effort="none",
        ),
        tools=[validate_symbol],
        system_prompt=planner_prompt,
        response_format=DownloadPlan,
    )

    planner_result = planner_agent.invoke(
        input={"messages": [HumanMessage(content=user_request)]}
        )

    return {
        "plan": planner_result["structured_response"],
        "messages": planner_result["messages"],
    }



"""## Agent 2 -- Downloader

**Role:** downloads and stores the data -- but only AFTER the plan is approved.
`compute_period_labels` deterministically computes the exact list of dates/months in plain
Python (rather than relying on the LLM to count dates correctly), and is capped by `max_files`
-- a safety parameter controlled by `execute_workflow`, NOT by the LLM. The Downloader agent gets
that exact list and calls `fetch_and_store_candles` once per item -- genuine tool-calling (ReAct)
behavior, but with a deterministically computed and bounded scope. The final report is built by
Python directly from the tool results (not from the LLM's free text), so the numbers are
guaranteed accurate.
"""

downloaded_data: dict[str, pd.DataFrame] = {}


def compute_period_labels(period_type: str, start_date: str, end_date: str, max_files: int) -> list[str]:

    labels = []

    if period_type == "daily":
        current = date.fromisoformat(start_date)
        end = date.fromisoformat(end_date)

        while (current <= end and len(labels) < max_files):
            labels.append(current.isoformat())
            current += timedelta(days=1)

    elif period_type == "monthly":
        year, month = (int(x) for x in start_date.split("-"))
        end_year, end_month = (int(x) for x in end_date.split("-"))

        while (year < end_year or (year == end_year and month <= end_month)) and len(labels) < max_files:
            labels.append(f"{year:04d}-{month:02d}")
            month += 1

            if month > 12:
                month = 1
                year += 1

    else:
        raise ValueError(f"Unsupported period_type: {period_type}")

    return labels

def download_binance_candles(symbol: str, interval: str, period_type: str, period_label: str):

    base_url = ("https://data.binance.vision/data")
    url = (f"{base_url}/spot/{period_type}/klines/{symbol}/{interval}/{symbol}-{interval}-{period_label}.zip")

    response = requests.get(url, timeout=60)

    if response.status_code == 404:

        return None, {
            "symbol": symbol,
            "interval": interval,
            "period_type": period_type,
            "period_label": period_label,
            "status": "not_found",
            "rows": 0,
        }

    response.raise_for_status()

    with zipfile.ZipFile(io.BytesIO(response.content)) as archive:

        csv_files = [name for name in archive.namelist() if name.endswith(".csv")]

        if not csv_files:
            raise ValueError("No CSV file found in archive.")

        csv_name = csv_files[0]

        with archive.open(csv_name) as csv_file:
            df = pd.read_csv(csv_file,header=None)

    # Binance historical cadle columns
    column_names = [ "open_time", "open", "high", "low", "close", "volume", "close_time", "quote_asset_volume", "number_of_trades", "taker_buy_base_volume", "taker_buy_quote_volume", "ignore" ]

    df.columns = column_names[:len(df.columns)]

    # Convert timestamp
    if not df.empty:
        if df["open_time"].max() > 10**14:
            df["open_time"] = pd.to_datetime(df["open_time"], unit="us", utc=True)
        else:
            df["open_time"] = pd.to_datetime(df["open_time"], unit="ms", utc=True)

    return df, {
        "symbol": symbol,
        "interval": interval,
        "period_type": period_type,
        "period_label": period_label,
        "status": "ok",
        "rows": len(df),
    }

def downloader_system_prompt(labels: list[str], plan: dict) -> str:

    return f"""
You are the Downloader Agent.

The human reviewer has APPROVED the following plan.

Symbol:
{plan["symbol"]}

Interval:
{plan["interval"]}

Period type:
{plan["period_type"]}

Start date:
{plan["start_date"]}

End date:
{plan["end_date"]}

You have been given this EXACT list of period labels:

{labels}

Your task is to download every requested period.

For EACH label:

- Call fetch_and_store_candles exactly once.
- Use the approved symbol.
- Use the approved interval.
- Use the approved period type.
- Use the current period label.

Rules:

- Do not invent labels.
- Do not skip labels.
- Do not download anything outside the list.
- Do not change the approved plan.
- Do not call the tool twice for the same label.

After all labels have been processed:

- Give a short summary.
- Report only information returned by the tool.
- Do not invent row counts.
"""

def downloader_agent(state: SystemState) -> dict:

    """
      Downloads and stores the data but only AFTER the plan is approved.
    """

    plan = state["plan"]

    if plan is None:
        raise ValueError("No approved download plan.")

    plan_dict = plan.model_dump()

    max_files = state.get("max_files", 5)

    labels = compute_period_labels(
        period_type=plan.period_type,
        start_date=plan.start_date,
        end_date=plan.end_date,
        max_files=max_files,
    )

    download_agent = create_agent(
        model=ChatOpenAI(
            model="gpt-5.6-luna",
            api_key=openai_api_key,
            reasoning_effort="none",
        ),
        tools=[fetch_and_store_candles],
        system_prompt=downloader_system_prompt(labels=labels, plan=plan_dict),
    )

    result = download_agent.invoke(
        input={
            "messages": [HumanMessage(content=("Execute the approved download plan for these labels: {labels}"))]
        }
    )

    messages = result["messages"]
    fetch_results = []

    for message in messages:

        if isinstance(message, ToolMessage):
            try:
                tool_result = json.loads(message.content)
                fetch_results.append(tool_result)

            except Exception:
                pass

    total_rows = sum(item.get("rows", 0) for item in fetch_results)

    files_ok = sum(1 for item in fetch_results if item.get("status") == "ok")

    files_missing = sum(1 for item in fetch_results if item.get("status") == "not_found")

    files_error = sum(1 for item in fetch_results if item.get("status") == "error")

    return {
        "download_summary": {
            "plan": plan_dict,
            "labels_requested": labels,
            "fetch_results": fetch_results,
            "total_rows": total_rows,
            "files_ok": files_ok,
            "files_missing": files_missing,
            "files_error": files_error,
        },
        "messages": messages,
    }

"""## Human-in-the-Loop Review

The review happens BEFORE the Downloader -- it approves the plan (symbol, interval, date range,
number of files), not the final report.
"""

def human_review(state: SystemState) -> dict:

    if state.get("autopilot"):
        return {
            "human_decision": {"approved": True, "feedback": ""}
            }

    plan = state["plan"]

    if plan is None:
        raise ValueError("No download plan available.")

    max_files = state.get("max_files",5)

    labels = compute_period_labels(
        period_type=plan.period_type,
        start_date=plan.start_date,
        end_date=plan.end_date,
        max_files=max_files,
    )

    decision = interrupt({
        "question": ("Approve this download plan? Reply with approved=True,or approved=False plus feedback."),
        "plan": plan.model_dump(),
        "files_to_download": labels,
        "file_count": len(labels),
    })

    return {"human_decision": decision}


def route_after_review(state: SystemState) -> str:

    decision = state.get("human_decision", {})

    if decision.get("approved"):
        return "downloader"

    return "apply_feedback"


def merge_feedback(state: SystemState) -> dict:

    decision = state.get("human_decision", {})

    feedback = decision.get("feedback", "").strip()

    history = list(state.get("feedback_history", []))

    if feedback:
        history.append(feedback)

    return {"feedback_history": history}

def report_node(state: SystemState) -> dict:

    summary = state["download_summary"]
    plan = summary["plan"]
    lines = [
        "### Download report", "",
      f"**Symbol:** {plan['symbol']} | **Interval:** {plan['interval']} | **Period type:** {plan['period_type']}",
      f"**Range:** {plan['start_date']} → {plan['end_date']}",
        "",
        "| Period | Status | Rows |",
        "|---|---|---:|",
    ]

    for result in summary["fetch_results"]:
        lines.append(f"| {result.get('period_label', '')} | {result.get('status', '')} | {result.get('rows', 0)} |")

    lines.extend(["",
                  f"**Total rows:** {summary['total_rows']}",
                  f"**Files OK:** {summary['files_ok']}  | **Missing:** {summary['files_missing']}  | **Errors:** {summary['files_error']}"
     ])

    draft_report = "\n".join(lines)

    return {
        "draft_report": draft_report,
        "messages": [AIMessage(content=draft_report)],
    }

"""## Building the LangGraph

Flow: `planner -> human_review -> (downloader -> report -> END) | (apply_feedback -> planner)`,
looping until the plan is approved. `MemorySaver` keeps state keyed by `thread_id`, which is what
makes the interrupt/resume mechanism possible.
"""

graph_builder = StateGraph(SystemState)
graph_builder.add_node("planner", planner)
graph_builder.add_node("human_review", human_review)
graph_builder.add_node("apply_feedback", merge_feedback)
graph_builder.add_node("downloader", downloader_agent)
graph_builder.add_node("report", report_node)

graph_builder.add_edge(START, "planner")
graph_builder.add_edge("planner", "human_review")
graph_builder.add_conditional_edges(
    "human_review",
    route_after_review,
    {"downloader": "downloader", "apply_feedback": "apply_feedback"})
graph_builder.add_edge("apply_feedback", "planner")
graph_builder.add_edge("downloader", "report")
graph_builder.add_edge("report", END)

checkpointer = MemorySaver()
graph = graph_builder.compile(checkpointer=checkpointer, debug=True)

display_graph(graph, Path("./graph.png"))

